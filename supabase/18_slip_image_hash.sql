-- 18) เพิ่มคอลัมน์ image_hash ในตาราง payment_slips เพื่อกันส่ง "สลิปรูปเดิม" ซ้ำ
--
--     ปัญหาที่พบ: ลองส่งสลิปรูปเดิมซ้ำ ระบบก็ยอมรับและบันทึกเข้า Supabase
--     ให้อีกแถวใหม่ทุกครั้ง ไม่มีการเช็คซ้ำเลย
--
--     สาเหตุ: ฟังก์ชัน check_duplicate_slip() ที่มีอยู่แล้ว (ไฟล์ 10_) เช็คซ้ำ
--     จาก reference_no / qr_transaction_id / (วันที่+เวลา+ยอดเงิน) เท่านั้น
--     แต่ 3 อย่างนี้จะมีค่าก็ต่อเมื่อสลิปมี QR Code ฝังอยู่ในรูป (ซึ่งสลิปจริง
--     ส่วนใหญ่ไม่มี) และแอปก็ไม่เคยมีการอ่าน OCR วันที่/เวลาออกมาจริง ๆ อยู่ดี
--     ผลคือ 3 เงื่อนไขนี้แทบไม่เคย match กันเลย ต่อให้เป็นรูปสลิปเดียวกันเป๊ะ ๆ
--
--     ทางแก้ที่ตรงจุดที่สุด: แฮชตัวไฟล์รูปสลิป (SHA-256) ตั้งแต่ฝั่งเบราว์เซอร์
--     ก่อนอัปโหลด แล้วเช็คว่ามีแฮชนี้ในระบบอยู่แล้วหรือยัง ถ้ามี = รูปเดิมเป๊ะ
--     ไม่ต้องพึ่ง QR/OCR เลย ครอบคลุมทุกกรณีที่ผู้เช่าส่งรูปเดิมซ้ำ
--
--     รันไฟล์นี้ใน Supabase SQL Editor ครั้งเดียว
-- ============================================================================

alter table public.payment_slips add column if not exists image_hash text;

create index if not exists idx_payment_slips_image_hash on public.payment_slips(image_hash);
