-- ค่าเน็ต/ค่าส่วนกลาง เดิมมี default ในตาราง rates เป็น 200/100 (จากตอนสร้างตาราง 1_schema.sql)
-- ทำให้ระบบคำนวณเอาไปรวมในบิลอัตโนมัติ ทั้งที่ยังไม่เคยมีช่องให้ตั้งค่าในหน้า "ตั้งค่าเรทบริการ" มาก่อน
-- ไฟล์นี้: 1) เปลี่ยน default คอลัมน์เป็น 0 (มีผลกับแถวใหม่ในอนาคตเท่านั้น)
--         2) รีเซ็ตแถวปัจจุบัน (id=1) เป็น 0 ให้ทันที เฉพาะกรณีที่ยังเป็นค่า default เดิม (200/100)
--            ที่ไม่เคยถูกตั้งค่าจริงจากหน้าตั้งค่าเลย (ป้องกันไม่ให้ไปทับค่าที่คุณตั้งไว้แล้วโดยไม่ตั้งใจ)

alter table public.rates alter column internet_fee set default 0;
alter table public.rates alter column common_fee  set default 0;

update public.rates
set internet_fee = 0
where id = 1 and internet_fee = 200;

update public.rates
set common_fee = 0
where id = 1 and common_fee = 100;

-- หลังรันไฟล์นี้ ให้เข้าหน้า "ตั้งค่าเรทบริการ" ในเว็บ (ที่อัปเดต app.js แล้ว) แล้วตั้งค่า
-- ค่าอินเทอร์เน็ต/ค่าส่วนกลางเองตามจริง (หรือเว้นว่าง/ใส่ 0 ถ้าไม่ต้องการคิดค่านี้) แล้วกด "บันทึกปรับเรทหลัก" อีกครั้ง
